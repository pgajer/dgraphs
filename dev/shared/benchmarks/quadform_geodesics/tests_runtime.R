test_that("campaign smoke resumes pending jobs only and exports full denominators", {
  output <- tempfile("qgs-campaign-"); on.exit(unlink(output, recursive = TRUE), add = TRUE)
  plan <- qgs.campaign.plan(x, pairs = data.frame(case_id = "flat2_ball", pair_id = "grid_direction"),
    repeats = 4101, bindings = c(I = "direct_connector", A = "direct_connector", B = "direct_connector"),
    cohorts = list(edge = list(metric = "edges", values = c(1, 2), limits = qgs.limits(list(seconds = 2)))),
    seconds = 1000, protocol = "harness-smoke-not-solver-evidence")
  qgs.campaign.create(home, file.path(fixture.home, "v1"), output, plan)
  initial <- qgs.campaign.read(output)
  expect_equal(sum(initial$state$status == "not_run"), 6)
  first <- qgs.campaign.run(home, output, max_jobs = 1)
  expect_equal(first$completed_this_call, 1)
  before <- digest::digest(file = file.path(output, "jobs/00001/record.rds"), algo = "sha256")
  second <- qgs.campaign.run(home, output)
  expect_equal(second$completed_this_call, 5)
  expect_gt(second$charged_seconds, first$charged_seconds)
  expect_identical(before, digest::digest(file = file.path(output, "jobs/00001/record.rds"), algo = "sha256"))
  state <- qgs.campaign.read(output)$state
  expect_true(all(state$status == "complete"))
  table <- read.csv(file.path(output, "checkpoints.csv"))
  expect_equal(nrow(table), 12)
  expect_true(all(table$audit_status == "passed"))
  expect_true(all(table$collection_gate == "consistent"))
  summary <- read.csv(file.path(output, "summary.csv"))
  expect_true(all(summary$planned == 1 & summary$usable == 1))
  expect_equal(nrow(read.csv(file.path(output, "fixture_exports/A-edge-4101-1.csv"))), 394)
  expect_true(all(read.csv(file.path(output, "paired.csv"))$difference_A_minus_B == 0))
  expect_true(all(read.csv(file.path(output, "directional.csv"))$relative_discrepancy == 0))
  expect_equal(qgs.campaign.run(home, output)$completed_this_call, 0)
  plan$seconds <- 999; saveRDS(plan, file.path(output, "plan.rds"))
  expect_error(qgs.campaign.read(output), "changed")
})
