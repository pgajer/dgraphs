test_that("binary keys are portable, preserve signed zeros and order by bytes", {
  expect_identical(qgs.vertex.key(c(0, -0)), "0000000200000000000000008000000000000000")
  expect_false(identical(qgs.vertex.key(c(0, 0)), qgs.vertex.key(c(0, -0))))
  key <- qgs.edge.key(c(-0.25, 0), c(0.25, 0))
  expect_identical(key$from, c(0.25, 0))
  expect_identical(key$key, qgs.edge.key(c(0.25, 0), c(-0.25, 0))$key)
  expect_equal(qgs.sum(c(1e16, 1, -1e16)), 1)
  before <- qgs.clock(); Sys.sleep(0.01)
  expect_gt(qgs.clock(), before)
})

test_that("LRU capacity, exact ordering and immutable snapshots are enforced", {
  r <- request(); control <- qgs.control.v2(r, capacity = 2)
  a <- c(0, 0); b <- c(0.1, 0); c <- c(0.2, 0); d <- c(0.3, 0)
  first <- control$edge(a, b); control$edge(a, c); control$edge(a, b); control$edge(a, d)
  expect_equal(control$stats()$evictions, 1)
  keys <- vapply(control$snapshot()$cache, `[[`, "", "key")
  expect_identical(keys, c(qgs.edge.key(a, b)$key, qgs.edge.key(a, d)$key))
  control$edge(a, c)
  expect_equal(control$stats()$edge_calls, 4)
  saved <- control$snapshot(adapter_state = list(stage = 1L, exclusions = "example", rng = "saved externally"))
  restored <- qgs.control.v2(r, restore = saved, capacity = 2)
  expect_identical(restored$snapshot()$cache, saved$cache)
  expect_equal(restored$stats()$edge_calls, 4)
  expect_gte(restored$stats()$algorithm_seconds, saved$elapsed)
  restored$edge(a, c, tighter = TRUE)
  expect_identical(first, list(length = 0.1, error_estimate = first$error_estimate))
  expect_identical(saved$adapter_state$stage, 1L)
  expect_error(qgs.control.v2(request(direction = "reverse"), restore = saved, capacity = 2), "mismatch")
})

test_that("durable algorithm checkpoints bind state without publishing an incumbent", {
  r <- request(); file <- tempfile("qgs-state-", fileext = ".rds")
  on.exit(unlink(file), add = TRUE)
  plain <- qgs.control(r)
  expect_identical(plain$capabilities()$checkpoint, "unavailable")
  expect_error(plain$checkpoint(list()), "unavailable")
  control <- qgs.control(r, persist.state = function(state) qgs.binary(state, file))
  expect_identical(control$capabilities()$cache_policy, "lru65536-levels01-v1")
  expect_identical(control$capabilities()$checkpoint, "adaptive-state-v1")
  e <- control$edge(r$from, r$to)
  control$publish(qgs.candidate(rbind(r$from, r$to), e$length, e$error_estimate), "initializer")
  incumbent <- control$latest()
  state <- list(schema = "adaptive-state-v1", rng_state = "exact serialized PCG64 state",
                queue = c(3L, 1L), exclusions = "edge", coordinates = c(0, -0))
  control$checkpoint(state)
  saved <- readRDS(file)
  expect_identical(saved$adapter_state, state)
  expect_identical(saved$latest, incumbent)
  expect_identical(control$latest(), incumbent)
  expect_equal(saved$counts$commits, 1)
  expect_equal(length(saved$cache), 1)
  restored <- qgs.control(r, restore = saved)
  restored$edge(r$to, r$from)
  expect_equal(restored$stats()$edge_calls, 1)
  expect_false(control$capabilities()$interrupted_solver_resume)
  broken <- qgs.control(r, persist.state = function(state) stop("disk unavailable"))
  expect_error(broken$checkpoint(state), "disk unavailable")
  expect_null(broken$latest())
})

test_that("failed calls are cached and successful upgrades satisfy coarse requests", {
  invocations <- 0L
  kernel <- function(a, b, forms, scale, tighter, poll, count) {
    invocations <<- invocations + 1L
    if (!tighter) stop("deliberate quadrature failure")
    list(length = 1, error_estimate = 1e-14)
  }
  r <- request(); control <- qgs.control.v2(r, kernel = kernel)
  expect_error(control$edge(r$from, r$to), "deliberate", class = "qgs_edge_error")
  expect_error(control$edge(r$from, r$to), "deliberate", class = "qgs_edge_error")
  expect_equal(control$stats()$edge_calls, 1)
  expect_equal(control$stats()$failure_hits, 1)
  upgraded <- control$edge(r$from, r$to, tighter = TRUE)
  expect_identical(control$edge(r$from, r$to), upgraded)
  expect_equal(invocations, 2)
  expect_equal(control$stats()$upgrades, 1)
  expect_equal(control$stats()$cache_entries, 1)
})

test_that("batches sort and deduplicate full keys before evaluation", {
  seen <- character()
  kernel <- function(a, b, ...) { seen <<- c(seen, qgs.edge.key(a, b)$key); list(length = 1, error_estimate = 0) }
  r <- request(); control <- qgs.control.v2(r, kernel = kernel)
  edges <- list(list(from = c(-0.2, 0), to = c(0.2, 0)),
                list(from = c(0, 0), to = c(0.1, 0)),
                list(from = c(0.1, 0), to = c(0, 0)))
  result <- control$batch(edges)
  expected <- sort(unique(vapply(edges, function(e) qgs.edge.key(e$from, e$to)$key, "")), method = "radix")
  expect_identical(seen, expected)
  expect_identical(names(result), expected)
  expect_equal(control$stats()$edge_calls, 2)
})

test_that("budget checkpoints use the last fully committed eligible incumbent", {
  r <- request(); r$budget <- list(metric = "edges", values = c(1, 2, 3))
  now <- 0; control <- qgs.control.v2(r, clock = function() now)
  e <- control$edge(r$from, r$to)
  candidate <- qgs.candidate(rbind(r$from, r$to), e$length, e$error_estimate)
  control$publish(candidate, "initializer")
  control$edge(r$from, r$to, tighter = TRUE); control$publish(candidate, "search")
  cp <- control$finish("initializer_complete")
  expect_identical(cp[[1]]$event$phase, "initializer")
  expect_identical(cp[[2]]$event$phase, "search")
  expect_identical(cp[[3]]$status, "carried")
  expect_equal(cp[[1]]$event$counters$edge_calls, 1)
  r$budget <- list(metric = "seconds", values = c(1, 2, 3))
  now <- 0; control <- qgs.control.v2(r, clock = function() now)
  now <- 0.5; control$publish(candidate, "initializer")
  now <- 1.1; control$publish(candidate, "search")
  now <- 2.1; cp <- control$finish("memory_budget")
  expect_identical(cp[[1]]$event$phase, "initializer")
  expect_identical(cp[[2]]$event$phase, "search")
  expect_identical(cp[[3]]$status, "censored")
})

test_that("audit deduplicates paths, not estimates, and retains completed qualification", {
  r <- request(); good <- qgs.execute(adapter, r)$incumbent$candidate
  bad <- good; bad$length <- bad$length + 1
  answers <- qgs.audit.queue(list(initializer = good, terminal = bad, checkpoint = good), r)
  expect_identical(answers$initializer$status, "passed")
  expect_identical(answers$terminal$status, "length_mismatch")
  expect_identical(answers$checkpoint$status, "passed")
  expect_equal(answers$checkpoint$audit_calls_so_far, 1)
  expect_equal(answers$initializer$rounding_allowance,
    64 * .Machine$double.eps * 2 * max(r$length_scale, good$length))
  longer <- good; longer$path$vertices <- rbind(r$from, (r$from + r$to)/2, r$to)
  answers <- qgs.audit.queue(list(initializer = good, terminal = longer), r, calls = 1)
  expect_identical(answers$initializer$status, "passed")
  expect_identical(answers$terminal$status, "audit_unavailable_budget")
  expect_identical(answers$terminal$feasibility, "entire_lifted_segments_in_convex_domain")
})

test_that("supervisor enforces memory bounds without a large allocation", {
